import { addDays, parseISO, isBefore, isAfter, addWeeks, addMonths, startOfDay, format, isSameMonth } from 'date-fns';
import { db } from '../db/database';
import type { RecurringRule, Transaction } from '../db/models';

export class RecurringEngine {
  /**
   * Generates a list of Date objects representing the occurrences of a rule between fromDate and toDate (inclusive)
   */
  static getOccurrences(rule: RecurringRule, fromDate: Date, toDate: Date): Date[] {
    const occurrences: Date[] = [];
    let current = startOfDay(parseISO(rule.startDate));
    const end = rule.endDate ? startOfDay(parseISO(rule.endDate)) : null;
    const from = startOfDay(fromDate);
    const to = startOfDay(toDate);

    // Fast-forward 'current' to be >= fromDate
    while (isBefore(current, from)) {
      current = this.getNextOccurrence(rule, current);
    }

    // Collect occurrences up to toDate
    while (!isAfter(current, to)) {
      if (end && isAfter(current, end)) break;
      occurrences.push(current);
      current = this.getNextOccurrence(rule, current);
    }

    return occurrences;
  }

  static getNextOccurrence(rule: RecurringRule, current: Date): Date {
    const interval = rule.interval || 1;
    switch (rule.frequency) {
      case 'daily':
        return addDays(current, interval);
      case 'weekly':
        return addWeeks(current, interval);
      case 'monthly':
        return addMonths(current, interval);
      default:
        return addDays(current, 1);
    }
  }

  /**
   * Calculates the unrecorded accrued amount for recurring rules up to targetDate.
   * "Unrecorded" means occurrences that do NOT have a matching recorded Transaction.
   */
  static async getUnrecordedAccruedAmount(monthStart: Date, targetDate: Date): Promise<number> {
    const activeRules = await db.recurringRules.where('status').equals('active').toArray();
    
    // Get all transactions generated by recurring rules in this month
    const startStr = format(monthStart, 'yyyy-MM-dd');
    const endStr = format(targetDate, 'yyyy-MM-dd');
    
    const transactions = await db.transactions
      .where('date')
      .between(monthStart.getTime(), targetDate.getTime() + 86400000)
      .toArray();

    const recurringTxMap = new Set(
      transactions
        .filter(t => t.source === 'recurring' && t.recurringRuleId && t.occurrenceDate)
        .map(t => `${t.recurringRuleId}_${t.occurrenceDate}`)
    );

    let totalAccruedUnrecorded = 0;

    for (const rule of activeRules) {
      const occurrences = this.getOccurrences(rule, monthStart, targetDate);
      
      for (const occ of occurrences) {
        const occStr = format(occ, 'yyyy-MM-dd');
        // If there is NO transaction recorded for this specific occurrence, add to accrued
        if (!recurringTxMap.has(`${rule.id}_${occStr}`)) {
          totalAccruedUnrecorded += rule.amount;
        }
      }
    }

    return totalAccruedUnrecorded;
  }
}
